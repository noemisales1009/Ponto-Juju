-- ============================================
-- TABELAS: Usuários e Médicos
-- ============================================

-- ============================================
-- 1. CRIAR TABELA usuarios
-- ============================================
CREATE TABLE IF NOT EXISTS public.usuarios (
  user_id uuid not null default gen_random_uuid(),
  created_at timestamp with time zone not null default timezone('America/Sao_Paulo'::text, now()),
  nome text not null,
  setor text null,
  funcao text not null,
  email text not null,
  foto text null,
  ativo boolean null default true,
  setor_id bigint null,
  constraint usuarios_pkey primary key (user_id),
  constraint usuarios_setor_id_fkey foreign key (setor_id) references setor_juju (id),
  constraint usuarios_user_id_fkey foreign key (user_id) references auth.users (id) on update cascade on delete cascade
) TABLESPACE pg_default;

-- ✅ Índices para performance
CREATE INDEX IF NOT EXISTS idx_usuarios_email ON public.usuarios USING btree (email) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_usuarios_ativo ON public.usuarios USING btree (ativo) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_usuarios_setor_id ON public.usuarios USING btree (setor_id) TABLESPACE pg_default;

-- ============================================
-- 2. CRIAR TABELA medicos_juju
-- ============================================
CREATE TABLE IF NOT EXISTS public.medicos_juju (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone('America/Sao_Paulo'::text, now()),
  medico text null,
  user_id uuid null,
  banco text null,
  agencia text null,
  variacao text null,
  cpf text null,
  conta text null,
  constraint medicos_juju_pkey primary key (id),
  constraint unique_user_id_medico unique (user_id),
  constraint fk_user_id_medico foreign key (user_id) references usuarios (user_id) on update cascade on delete cascade
) TABLESPACE pg_default;

-- ✅ Índices para performance
CREATE INDEX IF NOT EXISTS idx_medicos_user_id ON public.medicos_juju USING btree (user_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_medicos_cpf ON public.medicos_juju USING btree (cpf) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_medicos_banco ON public.medicos_juju USING btree (banco) TABLESPACE pg_default;

-- ============================================
-- 3. FUNÇÃO: Auditoria de atualização de nome
-- ============================================
CREATE TABLE IF NOT EXISTS public.auditoria_medicos (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone('America/Sao_Paulo'::text, now()),
  medico_id bigint not null,
  nome_anterior text null,
  nome_novo text null,
  usuario_alterou uuid null,
  constraint auditoria_medicos_pkey primary key (id),
  constraint fk_medico_id foreign key (medico_id) references medicos_juju (id) on delete cascade
) TABLESPACE pg_default;

CREATE OR REPLACE FUNCTION public.fn_atualizar_nome_auditoria()
RETURNS TRIGGER AS $$
BEGIN
  -- Registra a alteração de nome na tabela de auditoria
  INSERT INTO public.auditoria_medicos (medico_id, nome_anterior, nome_novo)
  VALUES (NEW.id, OLD.medico, NEW.medico);
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================
-- 4. TRIGGER: Registrar auditoria ao atualizar nome
-- ============================================
DROP TRIGGER IF EXISTS trg_atualizar_nome_auditoria ON public.medicos_juju;

CREATE TRIGGER trg_atualizar_nome_auditoria
AFTER UPDATE OF medico ON public.medicos_juju
FOR EACH ROW
WHEN (OLD.medico IS DISTINCT FROM NEW.medico)
EXECUTE FUNCTION fn_atualizar_nome_auditoria();

-- ============================================
-- 5. VIEW: Médicos com informações completas
-- ============================================
CREATE OR REPLACE VIEW public.vw_medicos_completo AS
SELECT
  m.id,
  m.medico,
  m.user_id,
  m.banco,
  m.agencia,
  m.variacao,
  m.cpf,
  m.conta,
  m.created_at,
  u.nome AS usuario_nome,
  u.email,
  u.foto,
  u.setor,
  u.setor_id,
  u.ativo
FROM public.medicos_juju m
LEFT JOIN public.usuarios u ON m.user_id = u.user_id;

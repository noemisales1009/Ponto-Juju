-- ============================================
SET TIME ZONE 'America/Sao_Paulo';

-- ============================================
-- 1. CRIAR TABELA ponto_juju2
-- ============================================
CREATE TABLE IF NOT EXISTS public.ponto_juju2 (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone('America/Sao_Paulo'::text, now()),
  data timestamp with time zone null,
  turno text not null,
  turno_preenchido boolean null,
  user_id uuid null,
  setor_id bigint null,
  falta text null,
  data_dia date null,
  dia_semana_calculado text null,
  valor_plantao numeric null,
  periodo_id bigint null,
  constraint ponto_juju2_pkey primary key (id),
  constraint fk_periodo_id foreign key (periodo_id) references periodo_juju (id) on delete set null,
  constraint fk_setor_id foreign key (setor_id) references setor_juju (id),
  constraint fk_user_id foreign key (user_id) references auth.users (id)
) TABLESPACE pg_default;

-- ============================================
-- 2. CRIAR ÍNDICES
-- ============================================
CREATE INDEX IF NOT EXISTS idx_ponto_data ON public.ponto_juju2 USING btree (data) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_ponto_setor_id ON public.ponto_juju2 USING btree (setor_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_ponto_user_id ON public.ponto_juju2 USING btree (user_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_ponto_juju2_periodo_id ON public.ponto_juju2 USING btree (periodo_id) TABLESPACE pg_default;

-- ✅ ÍNDICE CRUCIAL: Evita duplicatas no mesmo dia
CREATE INDEX IF NOT EXISTS idx_ponto_user_dia_unico ON public.ponto_juju2 USING btree (user_id, data_dia) TABLESPACE pg_default;

-- ============================================
-- 3. FUNÇÃO: Validar ponto duplicado + Calcular valores
-- ============================================
CREATE OR REPLACE FUNCTION public.fn_ponto_total_automatizado()
RETURNS TRIGGER AS $$
DECLARE
    v_dia_semana TEXT;
    v_eh_noturno BOOLEAN;
    v_dia_num INT;
    v_periodo_id BIGINT;
    v_valor_periodo NUMERIC;
    v_turno_normalizado TEXT;
    v_count_ponto_dia INT;
BEGIN
    -- ⚠️ VALIDAÇÃO: Verificar se médico já bateu ponto hoje
    SELECT COUNT(*)
    INTO v_count_ponto_dia
    FROM public.ponto_juju2
    WHERE user_id = NEW.user_id
      AND data_dia = DATE(NEW.data)
      AND id != COALESCE(NEW.id, -1);  -- Exclude o próprio registro em UPDATE

    IF v_count_ponto_dia > 0 THEN
        RAISE EXCEPTION 'Médico já bateu ponto em %! Proibido bater ponto duas vezes no mesmo dia.', 
            DATE(NEW.data)
        USING ERRCODE = 'unique_violation';
    END IF;

    -- Data base
    NEW.data_dia := DATE(NEW.data);

    -- Detecta noturno (CORRETO)
    v_eh_noturno := (
        NEW.turno ILIKE '%noite%' OR
        NEW.turno ILIKE '%19h - 07h%' OR
        NEW.turno ILIKE '%19:00 - 07:00%' OR
        NEW.turno ILIKE '%21h%'
    );

    -- Dia da semana (prioridade texto)
    v_dia_semana := CASE
        WHEN NEW.turno ILIKE '%segunda%' THEN 'Segunda'
        WHEN NEW.turno ILIKE '%terça%' OR NEW.turno ILIKE '%terca%' THEN 'Terça'
        WHEN NEW.turno ILIKE '%quarta%' THEN 'Quarta'
        WHEN NEW.turno ILIKE '%quinta%' THEN 'Quinta'
        WHEN NEW.turno ILIKE '%sexta%' THEN 'Sexta'
        WHEN NEW.turno ILIKE '%sábado%' OR NEW.turno ILIKE '%sabado%' THEN 'Sábado'
        WHEN NEW.turno ILIKE '%domingo%' THEN 'Domingo'
        ELSE NULL
    END;

    -- Fallback pela data
    IF v_dia_semana IS NULL THEN
        v_dia_num := EXTRACT(ISODOW FROM NEW.data_dia);
        v_dia_semana := CASE v_dia_num
            WHEN 1 THEN 'Segunda'
            WHEN 2 THEN 'Terça'
            WHEN 3 THEN 'Quarta'
            WHEN 4 THEN 'Quinta'
            WHEN 5 THEN 'Sexta'
            WHEN 6 THEN 'Sábado'
            WHEN 7 THEN 'Domingo'
        END;
    END IF;

    NEW.dia_semana_calculado := v_dia_semana;

    -- Número do dia
    v_dia_num := CASE v_dia_semana
        WHEN 'Segunda' THEN 1
        WHEN 'Terça' THEN 2
        WHEN 'Quarta' THEN 3
        WHEN 'Quinta' THEN 4
        WHEN 'Sexta' THEN 5
        WHEN 'Sábado' THEN 6
        WHEN 'Domingo' THEN 7
    END;

    -- 🔁 NORMALIZA TURNO
    IF v_eh_noturno THEN
        IF v_dia_semana = 'Sexta' THEN
            v_turno_normalizado := 'Sexta noite (19h - 07h)';
        ELSIF v_dia_semana IN ('Sábado','Domingo') THEN
            v_turno_normalizado := 'Noite Final de Semana (19h - 07h)';
        ELSE
            v_turno_normalizado := 'Noite Semana (19h - 07h)';
        END IF;

    ELSIF NEW.turno ILIKE '%manhã%' OR NEW.turno ILIKE '%manha%' OR NEW.turno ILIKE '%07h%' THEN
        IF v_dia_semana IN ('Sábado','Domingo') THEN
            v_turno_normalizado := 'Manhã Final de Semana (07h - 13h)';
        ELSE
            v_turno_normalizado := 'Manhã Semana (07h - 13h)';
        END IF;

    ELSIF NEW.turno ILIKE '%tarde%' OR NEW.turno ILIKE '%13h%' OR NEW.turno ILIKE '%13:00%' THEN
        IF v_dia_semana IN ('Sábado','Domingo') THEN
            v_turno_normalizado := 'Tarde Final de Semana (13h - 19h)';
        ELSE
            v_turno_normalizado := 'Tarde Semana (13h - 19h)';
        END IF;

    ELSE
        v_turno_normalizado := NEW.turno;
    END IF;

    NEW.turno := v_turno_normalizado;

    -- 🔍 BUSCA ROBUSTA EM periodo_juju
    SELECT p.id, p.valor_por_plantao
    INTO v_periodo_id, v_valor_periodo
    FROM periodo_juju p
    WHERE p.setor_id = NEW.setor_id
      AND REGEXP_REPLACE(UPPER(p.periodo), '[^A-Z0-9]', '', 'g')
          = REGEXP_REPLACE(UPPER(NEW.turno), '[^A-Z0-9]', '', 'g')
    LIMIT 1;

    IF v_periodo_id IS NOT NULL THEN
        NEW.periodo_id := v_periodo_id;
        NEW.valor_plantao := v_valor_periodo;
        RETURN NEW;
    END IF;

    -- ⚠️ FALLBACK (caso não encontre período)
    IF NEW.setor_id = 3 THEN
        IF v_eh_noturno THEN
            NEW.valor_plantao := CASE 
                WHEN v_dia_num = 5 THEN 2000
                WHEN v_dia_num IN (6,7) THEN 2400
                ELSE 1900
            END;
        ELSE
            NEW.valor_plantao := CASE 
                WHEN v_dia_num IN (6,7) THEN 950
                ELSE 875
            END;
        END IF;
    END IF;

    IF NEW.setor_id = 2 THEN
        IF v_eh_noturno THEN
            NEW.valor_plantao := CASE 
                WHEN v_dia_num IN (5,6,7) THEN 1900
                ELSE 1800
            END;
        ELSE
            NEW.valor_plantao := CASE 
                WHEN v_dia_num IN (6,7) THEN 925
                ELSE 825
            END;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ============================================
-- 4. TRIGGER: Executar função antes de INSERT ou UPDATE
-- ============================================
DROP TRIGGER IF EXISTS trg_ponto_completo_juju ON public.ponto_juju2;

CREATE TRIGGER trg_ponto_completo_juju
BEFORE INSERT OR UPDATE
ON public.ponto_juju2
FOR EACH ROW
EXECUTE FUNCTION fn_ponto_total_automatizado();


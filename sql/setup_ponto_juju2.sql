ALTER TABLE public.ponto_juju2
ADD CONSTRAINT unique_ponto_user_dia UNIQUE (user_id, data_dia);

-- ============================================
-- 6. TABELA: Registrar faltas dos médicos (SIMPLIFICADA)
-- ============================================
CREATE TABLE IF NOT EXISTS public.falta_medico (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone('America/Sao_Paulo'::text, now()),
  user_id uuid not null,
  data_falta date not null,
  constraint falta_medico_pkey primary key (id),
  constraint fk_falta_user_id foreign key (user_id) references auth.users (id) on delete cascade
) TABLESPACE pg_default;

-- ✅ Índices para performance
CREATE INDEX IF NOT EXISTS idx_falta_user_id ON public.falta_medico USING btree (user_id) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_falta_data ON public.falta_medico USING btree (data_falta) TABLESPACE pg_default;
CREATE INDEX IF NOT EXISTS idx_falta_user_data ON public.falta_medico USING btree (user_id, data_falta) TABLESPACE pg_default;

-- ✅ CONSTRAINT: Um médico só pode registrar uma falta por dia
ALTER TABLE public.falta_medico
ADD CONSTRAINT unique_falta_user_dia UNIQUE (user_id, data_falta);

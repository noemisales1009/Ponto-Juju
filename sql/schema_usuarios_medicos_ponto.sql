-- ============================================
-- TABELA: public.usuarios
-- ============================================
create table public.usuarios (
  user_id uuid not null default gen_random_uuid (),
  created_at timestamp with time zone not null default timezone ('America/Sao_Paulo'::text, now()),
  nome text not null,
  setor text null,
  funcao text not null,
  email text not null,
  foto text null,
  ativo boolean null default true,
  setor_id bigint null,
  constraint usuarios_pkey primary key (user_id),
  constraint usuarios_user_id_fkey foreign KEY (user_id) references auth.users (id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create index IF not exists idx_usuarios_email on public.usuarios using btree (email) TABLESPACE pg_default;

create index IF not exists idx_usuarios_ativo on public.usuarios using btree (ativo) TABLESPACE pg_default;

create index IF not exists idx_usuarios_setor_id on public.usuarios using btree (setor_id) TABLESPACE pg_default;


-- ============================================
-- TABELA: public.medicos_juju
-- ============================================
create table public.medicos_juju (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone ('America/Sao_Paulo'::text, now()),
  medico text null,
  user_id uuid null,
  banco text null,
  agencia text null,
  variacao text null,
  cpf text null,
  conta text null,
  constraint medicos_juju_pkey primary key (id),
  constraint unique_user_id_medico unique (user_id),
  constraint fk_user_id_medico foreign KEY (user_id) references usuarios (user_id) on update CASCADE on delete CASCADE
) TABLESPACE pg_default;

create index IF not exists idx_medicos_user_id on public.medicos_juju using btree (user_id) TABLESPACE pg_default;

create index IF not exists idx_medicos_cpf on public.medicos_juju using btree (cpf) TABLESPACE pg_default;

create index IF not exists idx_medicos_banco on public.medicos_juju using btree (banco) TABLESPACE pg_default;

create trigger trg_atualizar_nome_auditoria
after
update OF medico on medicos_juju for EACH row when (old.medico is distinct from new.medico)
execute FUNCTION fn_atualizar_nome_auditoria ();


-- ============================================
-- TABELA: public.ponto_juju2
-- ============================================
create table public.ponto_juju2 (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone ('America/Sao_Paulo'::text, now()),
  data timestamp with time zone null,
  turno text not null,
  turno_preenchido boolean null,
  user_id uuid null,
  setor_id bigint null,
  falta text null,
  data_dia date null,
  dia_semana_calculado text null,
  valor_plantao numeric null,
  periodo_id bigint null,
  constraint ponto_juju2_pkey primary key (id),
  constraint unique_ponto_user_dia unique (user_id, data_dia),
  constraint fk_periodo_id foreign KEY (periodo_id) references periodo_juju (id) on delete set null,
  constraint fk_setor_id foreign KEY (setor_id) references setor_juju (id),
  constraint fk_user_id foreign KEY (user_id) references auth.users (id)
) TABLESPACE pg_default;

create index IF not exists idx_ponto_data on public.ponto_juju2 using btree (data) TABLESPACE pg_default;

create index IF not exists idx_ponto_setor_id on public.ponto_juju2 using btree (setor_id) TABLESPACE pg_default;

create index IF not exists idx_ponto_user_id on public.ponto_juju2 using btree (user_id) TABLESPACE pg_default;

create index IF not exists idx_ponto_juju2_periodo_id on public.ponto_juju2 using btree (periodo_id) TABLESPACE pg_default;

create index IF not exists idx_ponto_user_dia_unico on public.ponto_juju2 using btree (user_id, data_dia) TABLESPACE pg_default;

create trigger trg_ponto_completo_juju BEFORE INSERT
or
update on ponto_juju2 for EACH row
execute FUNCTION fn_ponto_total_automatizado ();

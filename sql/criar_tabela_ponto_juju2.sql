-- ============================================
-- TABELA: public.ponto_juju2
-- DEFINIÇÃO REAL, copiada do banco em produção (referência; não precisa executar).
--
-- Pontos para conhecer:
--  * data_dia é calculado pelo trigger (fn_ponto_total_automatizado) a partir de "data".
--    Por isso o app envia sempre "data" junto (ao meio-dia UTC) e data_dia.
--  * turno é normalizado pelo trigger ("Manhã" -> "Manhã Semana (07h - 13h)" etc.).
--  * falta: NULL = presente, 'Sim' = falta (sem restrição no banco; ver ETAPA_1_seguranca.sql).
--  * created_by = quem registrou (padrão auth.uid()); controla quem pode editar/apagar.
--  * unique (user_id, data_dia, turno): um médico pode ter vários turnos no dia, mas não repetir o turno.
--  * created_at usa timezone('America/Sao_Paulo', now()) numa coluna timestamptz: o valor
--    fica 3 horas atrás do instante real. O app não usa created_at.
-- ============================================

create table public.ponto_juju2 (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default timezone ('America/Sao_Paulo'::text, now()),
  data timestamp with time zone null,
  turno text not null,
  turno_preenchido boolean null,
  user_id uuid null,
  setor_id bigint null,
  falta text null,
  data_dia date null,
  dia_semana_calculado text null,
  valor_plantao numeric null,
  periodo_id bigint null,
  created_by uuid not null default auth.uid (),
  constraint ponto_juju2_pkey primary key (id),
  constraint unique_ponto_user_dia_turno unique (user_id, data_dia, turno),
  constraint fk_periodo_id foreign KEY (periodo_id) references periodo_juju (id) on delete set null,
  constraint fk_setor_id foreign KEY (setor_id) references setor_juju (id),
  constraint fk_user_id foreign KEY (user_id) references auth.users (id),
  constraint ponto_juju2_created_by_fkey foreign KEY (created_by) references auth.users (id)
) TABLESPACE pg_default;

create index IF not exists idx_ponto_setor_data_dia on public.ponto_juju2 using btree (setor_id, data_dia desc) TABLESPACE pg_default;

create index IF not exists idx_ponto_data_dia on public.ponto_juju2 using btree (data_dia desc) TABLESPACE pg_default;

create index IF not exists idx_ponto_created_by on public.ponto_juju2 using btree (created_by) TABLESPACE pg_default;

create index IF not exists idx_ponto_setor_id on public.ponto_juju2 using btree (setor_id) TABLESPACE pg_default;

create index IF not exists idx_ponto_user_id on public.ponto_juju2 using btree (user_id) TABLESPACE pg_default;

create index IF not exists idx_ponto_juju2_periodo_id on public.ponto_juju2 using btree (periodo_id) TABLESPACE pg_default;

create trigger trg_ponto_completo_juju BEFORE INSERT
or
update on ponto_juju2 for EACH row
execute FUNCTION fn_ponto_total_automatizado ();
